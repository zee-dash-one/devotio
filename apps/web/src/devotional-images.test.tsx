import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { DevotionalImages } from "./pages/devotional-images";
import { imageRevision, type DevotionalImageManifest } from "domain/core";
const state = vi.hoisted(() => ({ repository: { watchDevotionalImages: vi.fn() } }));
vi.mock("./context", () => ({ useApp: () => ({ repository: state.repository }) }));
const day = { id: "day", date: "2026-10-25", reference: "João 1:1", reflection: "Reflexão", prayerSuggestion: "Oração", scripture: "Texto", translation: "ARC", credit: "Equipe" };
beforeEach(() => {
  HTMLDialogElement.prototype.showModal = function () { this.setAttribute("open", ""); };
  HTMLDialogElement.prototype.close = function () { this.removeAttribute("open"); };
});
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it("downloads only the selected variant, shares prepared files and releases preview URLs", async () => {
  const manifest: DevotionalImageManifest = { revision: imageRevision(day), status: "ready", files: ["story-paper", "story-forest", "square-paper"].map(variant => ({ variant, page: 1, pages: 1, width: 1080, height: 1920, bytes: 4, url: "https://images.example/"+variant })) };
  state.repository.watchDevotionalImages.mockImplementation(() => (next: (value: DevotionalImageManifest) => void) => { next(manifest); return () => {}; });
  let release: (value: unknown) => void = () => {};
  const fetchMock = vi.fn().mockImplementation(() => new Promise(resolve => { release = resolve; }));
  vi.stubGlobal("fetch", fetchMock);
  const create = vi.fn().mockReturnValue("blob:prepared"), revoke = vi.fn();
  vi.stubGlobal("URL", Object.assign(URL, { createObjectURL: create, revokeObjectURL: revoke }));
  Object.defineProperty(navigator, "canShare", { configurable: true, value: () => true });
  const share = vi.fn().mockRejectedValue(Object.assign(new Error("Cancelado"), { name: "AbortError" }));
  Object.defineProperty(navigator, "share", { configurable: true, value: share });
  const download = vi.spyOn(HTMLAnchorElement.prototype, "click");
  const view = render(<DevotionalImages day={day} onClose={() => {}} />);
  await waitFor(() => expect(fetchMock).toHaveBeenCalledTimes(1));
  expect(fetchMock.mock.calls[0][0]).toBe("https://images.example/story-paper");
  expect((screen.getByRole("button", { name: "Compartilhar imagem" }) as HTMLButtonElement).disabled).toBe(true);
  release({ ok: true, blob: async () => new Blob(["png"], { type: "image/png" }) });
  await screen.findByRole("link", { name: "Baixar imagem" });
  fireEvent.click(screen.getByRole("button", { name: "Compartilhar imagem" }));
  expect(share).toHaveBeenCalledWith({ files: [expect.any(File)] });
  await waitFor(() => expect((screen.getByRole("button", { name: "Compartilhar imagem" }) as HTMLButtonElement).disabled).toBe(false));
  expect(download).not.toHaveBeenCalled(); expect(fetchMock).toHaveBeenCalledTimes(1);
  fireEvent.change(screen.getByLabelText("Arte"), { target: { value: "forest" } });
  await waitFor(() => expect(fetchMock).toHaveBeenCalledTimes(2));
  expect(fetchMock.mock.calls[0][1].signal.aborted).toBe(true);
  expect(revoke).toHaveBeenCalledWith("blob:prepared");
  view.unmount(); expect(fetchMock.mock.calls[1][1].signal.aborted).toBe(true);
  Object.defineProperty(navigator, "share", { configurable: true, value: undefined });
  Object.defineProperty(navigator, "canShare", { configurable: true, value: undefined });
});
